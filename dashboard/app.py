with tab4:
    st.subheader("Data Architecture, Metric Definitions & Dual SQL/Pandas Verification")
    
    st.markdown("""
    ### 1. Metric Definitions & Formulas
    - **MRR at Month-End**: Sum of active subscription list prices active on the final calendar day of the month:
      $$\\text{MRR}_m = \\sum_{s \\in \\text{Active}_m} \\text{monthly\\_price}_s$$
    - **Net New MRR**:
      $$\\text{Net New MRR} = \\text{New MRR} + \\text{Expansion MRR} - \\text{Contraction MRR} - \\text{Churned MRR}$$
    - **Reconciliation Identity**:
      $$\\text{Opening MRR}_m + \\text{Net New MRR}_m = \\text{Closing MRR}_m$$
    - **Logo Churn Rate**:
      $$\\text{Logo Churn Rate}_m = \\frac{\\text{Churned Customers}_m}{\\text{Opening Active Customers}_m}$$
    - **Net Revenue Retention (NRR)**:
      $$\\text{NRR}_m = \\frac{\\text{Opening MRR}_m + \\text{Expansion}_m - \\text{Contraction}_m - \\text{Churned}_m}{\\text{Opening MRR}_m}$$
    - **Gross Revenue Retention (GRR)**:
      $$\\text{GRR}_m = \\frac{\\text{Opening MRR}_m - \\text{Contraction}_m - \\text{Churned}_m}{\\text{Opening MRR}_m}$$
    - **Lifetime Value (LTV)**:
      $$\\text{LTV} = \\frac{\\text{ARPA} \\times \\text{Gross Margin %}}{\\text{Monthly Logo Churn Rate}}$$
    """)
    
    st.divider()
    
    st.markdown("### 2. Dual Engine Verification: MySQL 8 (via DuckDB) vs. Pandas")
